export function renderSessionSidebar(state: AppViewState) {
  const sessions = state.sessionsResult?.sessions ?? [];
  const sorted = [...sessions].toSorted((a, b) => (b.updatedAt ?? 0) - (a.updatedAt ?? 0));
  const mainSessionKey = resolveMainSessionKey(state.hello, state.sessionsResult) ?? "main";

  const onNewSession = () => {
    const key = `chat-${Date.now()}`;
    resetChatStateForSessionSwitch(state, key);
    void state.loadAssistantIdentity();
    syncUrlWithSessionKey(
      state as unknown as Parameters<typeof syncUrlWithSessionKey>[0],
      key,
      true,
    );
    void loadChatHistory(state as unknown as ChatState);
  };

  const onSelectSession = (key: string) => {
    if (key === state.sessionKey) {
      return;
    }
    resetChatStateForSessionSwitch(state, key);
    void state.loadAssistantIdentity();
    syncUrlWithSessionKey(
      state as unknown as Parameters<typeof syncUrlWithSessionKey>[0],
      key,
      true,
    );
    void loadChatHistory(state as unknown as ChatState);
  };

  const onDeleteSession = async (key: string) => {
    const deleted = await deleteSessionAndRefresh(
      state as unknown as Parameters<typeof deleteSessionAndRefresh>[0],
      key,
    );
    if (deleted && state.sessionKey === key) {
      onSelectSession(mainSessionKey);
    }
  };

  const onRenameSession = (key: string, el: HTMLElement) => {
    const nameSpan = el
      .closest(".session-sidebar__item")
      ?.querySelector(".session-sidebar__item-name") as HTMLElement | null;
    if (!nameSpan) {
      return;
    }
    const currentName = nameSpan.textContent?.trim() ?? "";
    const input = document.createElement("input");
    input.type = "text";
    input.className = "session-sidebar__rename-input";
    input.value = currentName;
    nameSpan.replaceWith(input);
    input.focus();
    input.select();
    const commit = () => {
      const newName = input.value.trim();
      if (newName && newName !== currentName) {
        void patchSession(state as unknown as Parameters<typeof patchSession>[0], key, {
          displayName: newName,
        });
      }
      input.replaceWith(nameSpan);
      if (newName) {
        nameSpan.textContent = newName;
      }
    };
    input.addEventListener("blur", commit, { once: true });
    input.addEventListener("keydown", (e) => {
      if (e.key === "Enter") {
        e.preventDefault();
        input.blur();
      }
      if (e.key === "Escape") {
        input.removeEventListener("blur", commit);
        input.replaceWith(nameSpan);
      }
    });
  };

  let searchQuery = "";

  return html`
    <div class="session-sidebar">
      <button class="session-sidebar__new-btn" @click=${onNewSession} title="New chat session">
        ${plusIcon}
        <span>New Chat</span>
      </button>
      <input
        type="text"
        class="session-sidebar__search"
        placeholder="Search sessions..."
        @input=${(e: Event) => {
          searchQuery = (e.target as HTMLInputElement).value.toLowerCase().trim();
          const items = (e.target as HTMLElement)
            .closest(".session-sidebar")
            ?.querySelectorAll(".session-sidebar__item");
          items?.forEach((item) => {
            const name =
              item.querySelector(".session-sidebar__item-name")?.textContent?.toLowerCase() ?? "";
            const key = item.getAttribute("title")?.toLowerCase() ?? "";
            item.style.display =
              !searchQuery || name.includes(searchQuery) || key.includes(searchQuery) ? "" : "none";
          });
        }}
      />
      <div class="session-sidebar__list">
        ${
          sorted.length === 0
            ? html`
                <div class="session-sidebar__empty">No sessions yet</div>
              `
            : repeat(
                sorted,
                (s) => s.key,
                (s) => {
                  const isActive = s.key === state.sessionKey;
                  const displayName = resolveSessionDisplayName(s.key, s);
                  const timeLabel = formatSessionTime(s.updatedAt);
                  const matchesSearch =
                    !searchQuery ||
                    displayName.toLowerCase().includes(searchQuery) ||
                    s.key.toLowerCase().includes(searchQuery);
                  return html`
                  <div
                    class="session-sidebar__item ${isActive ? "session-sidebar__item--active" : ""}"
                    @click=${() => onSelectSession(s.key)}
                    title=${s.key}
                    style=${matchesSearch ? "" : "display:none"}
                  >
                    <div class="session-sidebar__item-content">
                      <span class="session-sidebar__item-icon">${icons.messageSquare}</span>
                      <span class="session-sidebar__item-name" @dblclick=${(e: Event) => {
                        e.stopPropagation();
                        onRenameSession(s.key, e.target as HTMLElement);
                      }}>${displayName}</span>
                    </div>
                    <div class="session-sidebar__item-meta">
                      <span class="session-sidebar__item-time">${timeLabel}</span>
                      ${
                        s.key !== mainSessionKey
                          ? html`<button
                            class="session-sidebar__item-delete"
                            @click=${(e: Event) => {
                              e.stopPropagation();
                              void onDeleteSession(s.key);
                            }}
                            title="Delete session"
                          >${trashIcon}</button>`
                          : nothing
                      }
                    </div>
                  </div>
                `;
                },
              )
        }
      </div>
    </div>
  `;
}
